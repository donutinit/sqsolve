// superuser connects as postgres over the socket, closed at the end.
func superuser(t *testing.T, c *testpg.Cluster) *pgx.Conn {
	t.Helper()
	conn, err := c.Connect(context.Background(), pg.Superuser, c.SuperPass, "postgres")
	if err != nil {
		t.Fatalf("superuser over the socket: %v\n%s", err, c.Log())
	}
	t.Cleanup(func() { conn.Close(context.Background()) })
	return conn
}

func pgCode(err error) string {
	var pe *pgconn.PgError
	if errors.As(err, &pe) {
		return pe.Code
	}
	return ""
}

// The cluster runs with the production configuration written by pgconf
// (its folders, socket, port, SCRAM, connection limits, memory) plus the
// two test-only speedups, the builtin C.UTF-8 collation and private files;
// the initdb password file does not stay behind.
func TestStartAppliesTheProductionConfiguration(t *testing.T) {
	ctx := context.Background()
	c := testpg.Start(t)
	conn := superuser(t, c)
	for name, want := range map[string]string{
		"data_directory":          c.DataDir,
		"hba_file":                filepath.Join(c.ConfDir, "pg_hba.conf"),
		"ident_file":              filepath.Join(c.ConfDir, "pg_ident.conf"),
		"config_file":             filepath.Join(c.ConfDir, "postgresql.conf"),
		"listen_addresses":        "127.0.0.1",
		"port":                    fmt.Sprint(c.Port),
		"unix_socket_directories": c.SocketDir,
		"password_encryption":     "scram-sha-256",
		"max_connections":         "50",
		"reserved_connections":    "3",
		"shared_buffers":          "64MB",
		"ssl":                     "off",
		"fsync":                   "off",
		"full_page_writes":        "off",
		"server_encoding":         "UTF8",
	} {
		var got string
		if err := conn.QueryRow(ctx, "SELECT current_setting($1)", name).Scan(&got); err != nil || got != want {
			t.Errorf("%s = %q, want %q (%v)", name, got, want, err)
		}
	}
	var provider, locale string
	if err := conn.QueryRow(ctx, `SELECT datlocprovider::text, datlocale FROM pg_database WHERE datname = 'postgres'`).Scan(&provider, &locale); err != nil || provider != "b" || locale != "C.UTF-8" {
		t.Errorf("collation %q %q: %v", provider, locale, err)
	}
	hba, _ := pgconf.HBA(pgconf.HBAOptions{})
	if b, err := os.ReadFile(filepath.Join(c.ConfDir, "pg_hba.conf")); err != nil || string(b) != hba {
		t.Errorf("pg_hba.conf is not the production one: %v\n%s", err, b)
	}
	conf, _ := os.ReadFile(filepath.Join(c.ConfDir, "postgresql.conf"))
	if !strings.HasPrefix(string(conf), "# Generated by sqsolve init.") || !strings.HasSuffix(string(conf), "fsync = off\nfull_page_writes = off\n") {
		t.Errorf("postgresql.conf:\n%s", conf)
	}
	for _, f := range []string{"postgresql.conf", "pg_hba.conf", "pg_ident.conf"} {
		if st, err := os.Stat(filepath.Join(c.ConfDir, f)); err != nil || st.Mode().Perm() != 0o600 {
			t.Errorf("%s: %v %v", f, st, err)
		}
	}
	if _, err := os.Stat(filepath.Join(c.Base, "pw")); !os.IsNotExist(err) {
		t.Errorf("the password file stayed: %v", err)
	}
	if _, err := os.Stat(filepath.Join(c.SocketDir, fmt.Sprintf(".s.PGSQL.%d", c.Port))); err != nil {
		t.Errorf("no socket: %v", err)
	}
	if !testpg.Contains(c.Log(), "database system is ready to accept connections") {
		t.Errorf("log:\n%s", c.Log())
	}
}

// The superuser password is checked over the socket, and the network is
// closed to the administrative roles; the generated admin password works
// for sqsolve_admin and a library role with a generated password reaches
// its database over TCP once pg_hba.conf allows it.
func TestConnectionsWithTheGeneratedPasswords(t *testing.T) {
	ctx := context.Background()
	c := testpg.Start(t)
	if c.SuperPass.Reveal() == "" || c.AdminPass.Reveal() == "" || c.SuperPass.Reveal() == c.AdminPass.Reveal() {
		t.Fatal("the generated passwords are empty or equal")
	}
	if _, err := c.Connect(ctx, pg.Superuser, secrets.New("wrong"), "postgres"); pgCode(err) != "28P01" {
		t.Fatalf("a wrong password over the socket: %v", err)
	}
	if _, err := c.ConnectTCP(ctx, pg.Superuser, c.SuperPass, "postgres"); pgCode(err) != "28000" || !strings.Contains(err.Error(), "pg_hba.conf rejects connection") {
		t.Fatalf("the superuser over TCP: %v", err)
	}
	cl := pg.New(c.SocketDir, c.Port, c.AdminPass, c.SuperPass)
	if err := cl.Bootstrap(ctx); err != nil {
		t.Fatal(err)
	}
	if err := cl.Open(ctx); err != nil {
		t.Fatal(err)
	}
	defer cl.Close()
	admin, err := c.Connect(ctx, pg.AdminRole, c.AdminPass, "postgres")
	if err != nil {
		t.Fatalf("sqsolve_admin over the socket: %v", err)
	}
	admin.Close(ctx)
	pass := secrets.GeneratePassword(24)
	v, err := pg.ScramVerifier(pass)
	if err != nil {
		t.Fatal(err)
	}
	if err := cl.CreateLibraryRole(ctx, "demo", pg.RoleOptions{Verifier: v, Login: true, ConnLimit: -1}); err != nil {
		t.Fatal(err)
	}
	if err := cl.CreateDatabase(ctx, "demo", "demo"); err != nil {
		t.Fatal(err)
	}
	if _, err := c.ConnectTCP(ctx, "demo", pass, "demo"); pgCode(err) != "28000" {
		t.Fatalf("before the rule: %v", err)
	}
	hba, err := pgconf.HBA(pgconf.HBAOptions{Libraries: []pgconf.HBALibrary{{DB: "demo", Roles: []string{"demo"}}}})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := pgconf.WriteHBA(c.ConfDir, hba); err != nil {
		t.Fatal(err)
	}
	if err := cl.ReloadConf(ctx); err != nil {
		t.Fatal(err)
	}
	conn, err := c.ConnectTCP(ctx, "demo", pass, "demo")
	if err != nil {
		t.Fatalf("the library role over TCP: %v\n%s", err, c.Log())
	}
	var user, addr string
	if err := conn.QueryRow(ctx, `SELECT current_user, host(inet_client_addr())`).Scan(&user, &addr); err != nil || user != "demo" || addr != "127.0.0.1" {
		t.Fatalf("connected as %q from %q: %v", user, addr, err)
	}
	conn.Close(ctx)
	if _, err := c.ConnectTCP(ctx, "demo", secrets.New("wrong"), "demo"); pgCode(err) != "28P01" {
		t.Fatalf("a wrong password over TCP: %v", err)
	}
	if _, err := c.ConnectTCP(ctx, pg.AdminRole, c.AdminPass, "postgres"); pgCode(err) != "28000" {
		t.Fatalf("sqsolve_admin over TCP: %v", err)
	}
}

// Restart keeps the data and the same port; Stop shuts the server down
// (twice is harmless); the end of the test removes the cluster's folders
// and frees its port.
func TestRestartStopAndCleanup(t *testing.T) {
	ctx := context.Background()
	var c *testpg.Cluster
	t.Run("cluster", func(t *testing.T) {
		c = testpg.Start(t)
		conn := superuser(t, c)
		if _, err := conn.Exec(ctx, `CREATE TABLE kept (x int); INSERT INTO kept VALUES (42)`); err != nil {
			t.Fatal(err)
		}
		conn.Close(ctx)
		c.Restart(t)
		conn = superuser(t, c)
		var x int
		if err := conn.QueryRow(ctx, `SELECT x FROM kept`).Scan(&x); err != nil || x != 42 {
			t.Fatalf("after the restart: %d %v", x, err)
		}
		conn.Close(ctx)
		if n := strings.Count(c.Log(), "database system is ready to accept connections"); n != 2 {
			t.Fatalf("%d starts in the log, want 2", n)
		}
		c.Stop()
		if _, err := c.Connect(ctx, pg.Superuser, c.SuperPass, "postgres"); err == nil {
			t.Fatal("connected after Stop")
		}
		c.Stop()
	})
	for _, dir := range []string{c.Base, c.SocketDir} {
		if _, err := os.Stat(dir); !os.IsNotExist(err) {
			t.Errorf("%s is still there: %v", dir, err)
		}
	}
	l, err := net.Listen("tcp", fmt.Sprintf("127.0.0.1:%d", c.Port))
	if err != nil {
		t.Fatalf("the port is still taken: %v", err)
	}
	l.Close()
}

// The cleanup also stops a server that is still running when the test ends.
func TestCleanupStopsARunningServer(t *testing.T) {
	var c *testpg.Cluster
	t.Run("cluster", func(t *testing.T) { c = testpg.Start(t) })
	if _, err := c.Connect(context.Background(), pg.Superuser, c.SuperPass, "postgres"); err == nil {
		t.Fatal("the server outlived its test")
	}
	if _, err := os.Stat(c.DataDir); !os.IsNotExist(err) {
		t.Fatalf("the data folder is still there: %v", err)
	}
}

// SQSOLVE_TEST_PG_BIN wins when it has both programs; a folder with only
// one of them is skipped in favour of an installed PostgreSQL.
func TestBinDirPrefersTheEnvironment(t *testing.T) {
	installed := testpg.BinDir()
	if installed == "" {
		t.Skip("PostgreSQL is not installed")
	}
	both := t.TempDir()
	for _, p := range []string{"initdb", "postgres"} {
		os.WriteFile(filepath.Join(both, p), []byte("#!/bin/false\n"), 0o700)
	}
	t.Setenv("SQSOLVE_TEST_PG_BIN", both)
	if got := testpg.BinDir(); got != both {
		t.Fatalf("got %s, want %s", got, both)
	}
	half := t.TempDir()
	os.WriteFile(filepath.Join(half, "initdb"), []byte("#!/bin/false\n"), 0o700)
	t.Setenv("SQSOLVE_TEST_PG_BIN", half)
	if got := testpg.BinDir(); got != installed {
		t.Fatalf("got %s, want the installed %s", got, installed)
	}
}
